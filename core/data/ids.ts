import { randomBytes } from 'crypto';

/**
 * Идентификатор новой записи, сгенерированный в ядре ДО обращения к базе.
 * Нужен для идемпотентности при повторной доставке сообщения шины (ТЗ 3.6):
 * повтор операции `create` с тем же id не создаёт дубликат. Форма похожа на
 * cuid (префикс `c`, время, случайная часть), но это не cuid — база ждёт
 * любую уникальную строку.
 */
export function newId(): string {
  return 'c' + Date.now().toString(36) + randomBytes(9).toString('hex');
}
